const {_electron}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const tempRoot=path.resolve(os.tmpdir());
const data=fs.mkdtempSync(path.join(tempRoot,'noveltype-packaged-test-'));
const env={...process.env};delete env.ELECTRON_RUN_AS_NODE;delete env.NOVELTYPE_TEST_DATA;
(async()=>{let app;try{
  const executablePath=process.env.NOVELTYPE_PACKAGED_EXE||path.join(root,'dist/win-unpacked/NovelType.exe');
  // Electron applies this native switch before app code and the single-instance lock.
  // Do not add a packaged-app environment override or launch against a user's profile.
  app=await _electron.launch({executablePath,args:[`--user-data-dir=${data}`],env,timeout:30000});
  const paths=await app.evaluate(({app})=>({userData:app.getPath('userData'),sessionData:app.getPath('sessionData')}));
  assert.equal(path.resolve(paths.userData).toLowerCase(),path.resolve(data).toLowerCase(),'Packaged test must use its temporary userData directory');
  assert.equal(path.resolve(paths.sessionData).toLowerCase(),path.resolve(data).toLowerCase(),'Browser storage must stay in the temporary profile');
  const page=await app.firstWindow();await page.locator('#book-title').waitFor({state:'visible'});
  await page.locator('#story-stream').waitFor({state:'visible'});
  assert.ok(await page.locator('.story-passage').count()>0);
  assert.equal(await page.locator('#completion-next,#next,#previous').count(),0);
  const state=await page.evaluate(()=>window.novel.getState());
  assert.equal(state.settings.hasKey,false);
  assert.equal(state.books.length,1);assert.equal(state.books[0].demo,true);
  await page.waitForFunction(()=>document.querySelector('#source-text .source-highlight')?.textContent==='清晨');
  await page.locator('#typing-input').click();await page.locator('#typing-input').pressSequentially('at dawn, L');
  await page.waitForFunction(()=>document.querySelector('#source-text .source-highlight')?.textContent==='林舟');
  assert.equal(await page.locator('#source-text').textContent(),state.books[0].segments[0].source);
  assert.equal(await page.locator('.target-char.wrong').count(),0);
  assert.equal(await page.evaluate(()=>document.activeElement.id),'typing-input');
  assert.equal(fs.existsSync(path.join(data,'library.json')),true);
  const encryption=await app.evaluate(({safeStorage,app})=>({available:safeStorage.isEncryptionAvailable(),packaged:app.isPackaged,version:app.getVersion()}));
  assert.equal(encryption.available,true);assert.equal(encryption.packaged,true);
  assert.equal(encryption.version,require('../package.json').version);
  const typing=await page.evaluate(async()=>{const {TypingSession}=await import('./typing.mjs');const session=new TypingSession('Ab');session.input('aB',0);return {complete:session.complete,accuracy:session.snapshot(0).accuracy};});
  assert.deepEqual(typing,{complete:true,accuracy:100});
  const sandbox=await app.evaluate(({BrowserWindow})=>{
    const preferences=BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences();
    return {sandbox:preferences.sandbox,contextIsolation:preferences.contextIsolation,nodeIntegration:preferences.nodeIntegration};
  });
  assert.deepEqual(sandbox,{sandbox:true,contextIsolation:true,nodeIntegration:false});
  const bridge=await page.evaluate(()=>({frozen:Object.isFrozen(window.novel),read:typeof window.novel.getGameData,save:typeof window.novel.saveGameResult,require:typeof window.require,ipc:typeof window.ipcRenderer}));
  assert.deepEqual(bridge,{frozen:true,read:'function',save:'function',require:'undefined',ipc:'undefined'});
  await app.evaluate(({net})=>{globalThis.packagedGameRequests=0;net.fetch=async()=>{globalThis.packagedGameRequests++;throw new Error('Packaged smoke games must stay offline');};});
  const gameData=await page.evaluate(id=>window.novel.getGameData({bookId:id}),state.activeBookId);
  assert.ok(gameData.passages.length>0);assert.ok(gameData.passages.length<=96);
  assert.ok(!JSON.stringify(gameData).includes('apiKey'));

  await page.locator('#nav-games').click();
  await page.locator('#game-race-open').click();
  const target=await page.locator('#game-race-text').textContent();
  await page.locator('#game-start').click();
  await page.locator('#game-input').pressSequentially(target.slice(0,2).toUpperCase(),{delay:20});
  assert.equal(await page.locator('#game-race-text .is-wrong').count(),0);
  await page.locator('#game-pause').click();
  assert.equal(await page.locator('#game-input').isDisabled(),true);
  const pausedTime=await page.locator('#game-time').innerText();
  await page.waitForTimeout(150);assert.equal(await page.locator('#game-time').innerText(),pausedTime);
  await page.locator('#game-pause').click();assert.equal(await page.locator('#game-input').isDisabled(),false);
  await page.locator('#game-end').click();
  await page.waitForFunction(()=>document.querySelector('#game-save-status')?.textContent.includes('已保存'));
  await page.locator('#game-leave').click();

  await page.locator('#game-defense-open').click();await page.locator('#game-start').click();
  const enemy=await page.locator('.game-enemy-word').first().textContent();
  await page.locator('#game-input').pressSequentially(enemy.toUpperCase(),{delay:20});
  assert.match(await page.locator('#game-kills').textContent(),/^1\s*\//);
  assert.equal(await page.locator('#game-input').inputValue(),'');
  await page.locator('#game-pause').click();assert.equal(await page.locator('#game-input').isDisabled(),true);
  await page.locator('#game-end').click();
  await page.waitForFunction(()=>document.querySelector('#game-save-status')?.textContent.includes('已保存'));
  await page.locator('#game-leave').click();await page.locator('#game-map-open').click();
  assert.equal(await page.locator('.game-map-node').count(),12);
  assert.equal(await page.locator('.game-map-node[data-level-id="1"]').isEnabled(),true);
  assert.equal(await page.locator('.game-map-node[data-level-id="2"]').isDisabled(),true);
  fs.mkdirSync(path.join(root,'evidence'),{recursive:true});
  await page.screenshot({path:path.join(root,'evidence/packaged-game-map.png'),fullPage:true});
  await page.locator('#nav-reading').click();
  assert.equal(await page.locator('#typing-input').inputValue(),'at dawn, L');
  const afterGames=await page.evaluate(()=>window.novel.getState());
  assert.equal(afterGames.books[0].position,0);assert.deepEqual(afterGames.books[0].completed,[]);
  assert.deepEqual(afterGames.books[0].stats,state.books[0].stats);
  assert.equal(await app.evaluate(()=>globalThis.packagedGameRequests),0);
  const games={race:true,defense:true,mapNodes:12,pause:true,caseInsensitive:true,isolatedProgress:true,offline:true};
  const network={tested:false,reason:'Provider translation not tested; fresh isolated profile has no API credentials. Game paths verified without any fetch calls.'};
  fs.mkdirSync(path.join(root,'evidence'),{recursive:true});
  await page.screenshot({path:path.join(root,'evidence/packaged-desktop.png'),fullPage:true});
  fs.writeFileSync(path.join(root,'evidence/packaged-tests.json'),JSON.stringify({at:new Date().toISOString(),launch:true,isolatedUserData:true,continuousUI:true,caseInsensitive:true,chineseHighlight:true,encryption,sandbox,games,network,realTranslationVerified:false},null,2));
  console.log(JSON.stringify({packagedLaunch:true,isolatedUserData:true,continuousUI:true,caseInsensitive:true,chineseHighlight:true,encryption,sandbox,games,network,realTranslationVerified:false}));
}finally{
  if(app)await app.close();
  const cleanupPath=path.resolve(data);
  assert.equal(path.dirname(cleanupPath),tempRoot,'Only the generated temporary profile can be removed');
  assert.ok(path.basename(cleanupPath).startsWith('noveltype-packaged-test-'));
  fs.rmSync(cleanupPath,{recursive:true,force:true,maxRetries:5,retryDelay:100});
}})().catch(e=>{console.error(e);process.exitCode=1;});
